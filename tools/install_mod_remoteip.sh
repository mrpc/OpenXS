#!/bin/bash
# Enables mod_remoteip so Apache's %h (access log client IP) and
# ModSecurity's [client ...] field both report the REAL visitor IP
# instead of Cloudflare's own edge-node IP, for any site proxied
# through Cloudflare. Without this, every IP-based decision downstream
# (CSF bans, mod_security's own per-IP logging, OpenXS's own CSF
# auto-ban) is blind - it sees Cloudflare's shared edge infrastructure,
# not the actual attacker/visitor, and banning "the IP in the log"
# would ban Cloudflare's PoP for every other site it also serves.
#
# Confirmed by hand, 2026-10-24: mod_remoteip's .load file already
# existed on disk but was never enabled, and no CF-Connecting-IP
# handling existed anywhere - access logs on a real Cloudflare-fronted
# domain showed only Cloudflare's own edge IPs (162.158.x, 172.70.x, ...).
#
# Used both by install.sh (--with-remoteip) and the Webmin dashboard's
# "Install" button (install_mod_remoteip.cgi) - single source of truth.
set -euo pipefail

CONF_FILE=/etc/apache2/conf-available/openxs-remoteip-cloudflare.conf
IPS_V4_URL="https://www.cloudflare.com/ips-v4"
IPS_V6_URL="https://www.cloudflare.com/ips-v6"

echo "==> Enabling mod_remoteip..."
a2enmod remoteip

echo "==> Fetching Cloudflare's current published IP ranges..."
ranges=$(printf '%s\n%s\n' "$(curl -fsS "$IPS_V4_URL" 2>/dev/null)" "$(curl -fsS "$IPS_V6_URL" 2>/dev/null)")
if ! echo "$ranges" | grep -q '/'; then
    echo "Could not fetch Cloudflare's IP ranges (no outbound internet?) - using the last-known-good list baked into this script."
    ranges=$(cat <<'EOF'
173.245.48.0/20
103.21.244.0/22
103.22.200.0/22
103.31.4.0/22
141.101.64.0/18
108.162.192.0/18
190.93.240.0/20
188.114.96.0/20
197.234.240.0/22
198.41.128.0/17
162.158.0.0/15
104.16.0.0/13
104.24.0.0/14
172.64.0.0/13
131.0.72.0/22
2400:cb00::/32
2606:4700::/32
2803:f800::/32
2405:b500::/32
2405:8100::/32
2a06:98c0::/29
2c0f:f248::/32
EOF
)
fi

{
    echo "# Auto-generated by install_mod_remoteip.sh - re-run it to refresh"
    echo "# Cloudflare's IP ranges (they do change occasionally)."
    echo "RemoteIPHeader CF-Connecting-IP"
    while IFS= read -r range; do
        [ -n "$range" ] && echo "RemoteIPTrustedProxy $range"
    done <<< "$ranges"
} > "$CONF_FILE"
echo "Wrote $CONF_FILE ($(grep -c RemoteIPTrustedProxy "$CONF_FILE") range(s))"

a2enconf openxs-remoteip-cloudflare
apachectl configtest
systemctl reload apache2 2>/dev/null || service apache2 reload
echo "Apache reloaded."
