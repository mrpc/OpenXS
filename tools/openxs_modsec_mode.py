#!/usr/bin/env python3
"""Regenerates /etc/modsecurity/openxs-mode.conf from the plain
host-mode list at /etc/openxs/modsec_mode (one "<hostname> <mode>" per
line, blank lines and '#' comments ignored; mode is on/detection/off).

Lets an admin put ModSecurity into DetectionOnly (logs would-be blocks,
doesn't actually block) for one hostname while investigating false
positives - a real false positive is found this way and fixed with a
precise rule exclusion (see openxs_modsec_rule_exclusions.py), not left
in DetectionOnly forever, and not "fixed" by disabling protection
outright for a whole site. A bare '*' hostname sets the server-wide
default instead of modsecurity.conf's own (On), for incident response
across every domain on the box at once.

Only emits an override for hosts explicitly listed - doesn't touch
modsecurity.conf's own default for anything not listed here."""
import os

MODE_FILE = "/etc/openxs/modsec_mode"
OUTPUT_FILE = "/etc/modsecurity/openxs-mode.conf"
VALID_MODES = {"on": "On", "detection": "DetectionOnly", "off": "Off"}


def read_modes():
    """Returns a list of (hostname, mode) tuples, mode already validated
    against VALID_MODES - an unrecognized mode on a line is skipped
    (not silently coerced to something it didn't say)."""
    if not os.path.isfile(MODE_FILE):
        return []
    entries = []
    with open(MODE_FILE) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) != 2 or parts[1] not in VALID_MODES:
                continue
            entries.append((parts[0], parts[1]))
    return entries


def regenerate():
    entries = read_modes()
    lines = [
        "# Auto-generated by openxs_modsec_mode.py from",
        f"# {MODE_FILE} - edit that file, not this one directly,",
        "# it gets overwritten.",
        "",
    ]
    for host, mode in entries:
        directive = VALID_MODES[mode]
        if host == "*":
            lines.append(f"<IfModule security2_module>\n\tSecRuleEngine {directive}\n</IfModule>\n")
        else:
            cond = f'%{{HTTP_HOST}} == \'{host}\''
            lines.append(f'<IfModule security2_module>\n\t<If "{cond}">\n\t\tSecRuleEngine {directive}\n\t</If>\n</IfModule>\n')
    with open(OUTPUT_FILE, "w") as f:
        f.write("\n".join(lines) + "\n")
    return entries


if __name__ == "__main__":
    entries = regenerate()
    print("\n".join(f"{h}: {m}" for h, m in entries) or "(no overrides configured - every host uses modsecurity.conf's own default)")
