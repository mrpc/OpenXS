#!/usr/bin/env python3
"""Regenerates /etc/modsecurity/openxs-exclusions.conf from the plain
path-prefix list at /etc/openxs/modsec_exclusions (one per line, blank
lines and '#' comments ignored) - same convention as the project's
other plain-text config files (ignore, rules, path_settings).

Fully disables the ModSecurity rule engine (CRS included) for any
request whose path starts with a listed prefix - for real false
positives on first-party endpoints (analytics beacons, admin panels
with their own auth already in front, etc.), not a general-purpose
bypass. Each entry is its own <LocationMatch> block so one broken line
can't accidentally swallow more than intended.
"""
import os
import re

EXCLUSIONS_FILE = "/etc/openxs/modsec_exclusions"
OUTPUT_FILE = "/etc/modsecurity/openxs-exclusions.conf"


def read_exclusions():
    if not os.path.isfile(EXCLUSIONS_FILE):
        return []
    paths = []
    with open(EXCLUSIONS_FILE) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                paths.append(line)
    return paths


def regenerate():
    paths = read_exclusions()
    lines = [
        "# Auto-generated by openxs_modsec_exclusions.py from",
        f"# {EXCLUSIONS_FILE} - edit that file, not this one directly,",
        "# it gets overwritten.",
        "",
    ]
    for p in paths:
        # Escape regex metacharacters in the path itself - this is a
        # literal prefix list, not a place for users to accidentally
        # write a regex that matches more than they meant.
        escaped = re.escape(p)
        lines.append(f'<LocationMatch "^{escaped}">')
        lines.append("\tSecRuleEngine Off")
        lines.append("</LocationMatch>")
        lines.append("")
    with open(OUTPUT_FILE, "w") as f:
        f.write("\n".join(lines) + "\n")
    return paths


if __name__ == "__main__":
    print("\n".join(regenerate()) or "(no exclusions configured)")
